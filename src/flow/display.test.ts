import { describe, it, expect } from 'vitest';

import { hpBar } from './display.js';

describe('hpBar', () => {
  it('正常血量', () => {
    expect(hpBar(1, 4)).toBe('❤️🖤🖤🖤 (1/4)');
  });

  it('负数血量 → 无红心，数值如实显示', () => {
    expect(hpBar(-2, 3)).toBe('🖤🖤🖤 (-2/3)');
  });

  it('零血量', () => {
    expect(hpBar(0, 3)).toBe('🖤🖤🖤 (0/3)');
  });

  it('越界血量（异常输入）→ 满红心，数值如实显示', () => {
    expect(hpBar(5, 3)).toBe('❤️❤️❤️ (5/3)');
  });
});
